const seedEvent = (
  seq: number,
  applicationId: string,
  action: AuditEvent["action"],
  timestamp: string,
  actor: string,
  role: AuditEvent["role"],
  metadata: Record<string, unknown>,
): AuditEvent => ({
  id: `EVT-S${String(seq).padStart(4, "0")}`,
  timestamp,
  actor,
  role,
  action,
  applicationId,
  metadata,
});

/** Derives the system-generated audit history implied by the seed applications. */
export function buildSeedAuditEvents(applications: Application[]): AuditEvent[] {
  let seq = 0;
  const events: AuditEvent[] = [];
  for (const app of applications) {
    const submitted = new Date(app.submittedAt).getTime();
    events.push(
      seedEvent(++seq, app.id, "APPLICATION_SUBMITTED", app.submittedAt, "onboarding-api", "SYSTEM", {
        channel: app.channel,
        product: app.product,
        ip: app.applicant.ipAddress,
      }),
      seedEvent(++seq, app.id, "RISK_SCORED", new Date(submitted + 4_000).toISOString(), "risk-engine", "SYSTEM", {
        score: app.risk.score,
        tier: app.risk.tier,
        primaryFlag: app.risk.primaryFlag,
        model: app.risk.modelVersion,
      }),
    );
    for (const n of app.notes) {
      events.push(
        seedEvent(++seq, app.id, "NOTE_ADDED", n.createdAt, n.author, n.role, {
          noteId: n.id,
          length: n.body.length,
        }),
      );
    }
    if (app.decision) {
      events.push(
        seedEvent(++seq, app.id, "STATUS_UPDATED", app.decision.decidedAt, app.decision.decidedBy, app.decision.role, {
          from: "Under Review",
          to: app.decision.outcome,
          ...(app.decision.reasonCode ? { reasonCode: app.decision.reasonCode } : {}),
        }),
      );
    }
  }
  return events.sort((a, b) => a.timestamp.localeCompare(b.timestamp));
}
